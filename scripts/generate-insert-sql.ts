import { readFileSync, writeFileSync, mkdirSync } from 'fs';

const csvPath = 'scripts/washington_resources_missing_supabase_ready_enriched_2026-08-30.csv';
const outDir = 'scripts/csv_batches';
mkdirSync(outDir, { recursive: true });

function parseCSV(text: string): string[][] {
  const rows: string[][] = [];
  let current: string[] = [];
  let field = '';
  let inQuotes = false;
  let i = 0;
  while (i < text.length) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 2; continue; }
        else { inQuotes = false; i++; continue; }
      } else { field += char; i++; continue; }
    }
    if (char === '"') { inQuotes = true; i++; continue; }
    if (char === ',') { current.push(field); field = ''; i++; continue; }
    if (char === '\r') { i++; continue; }
    if (char === '\n') { current.push(field); rows.push(current); current = []; field = ''; i++; continue; }
    field += char; i++;
  }
  if (field.length > 0 || current.length > 0) { current.push(field); rows.push(current); }
  return rows;
}

function parseArrayField(val: string): string[] {
  if (!val || val === '[]') return [];
  try {
    const parsed = JSON.parse(val);
    return Array.isArray(parsed) ? parsed.map(String) : [];
  } catch { return []; }
}

function parseBool(val: string): boolean {
  return val === 'true' || val === 'TRUE' || val === 'True' || val === '1';
}

function parseFloatOrNull(val: string): number | null {
  if (val === '' || val === 'null') return null;
  const n = parseFloat(val);
  return isNaN(n) ? null : n;
}

function parseStringOrNull(val: string): string | null {
  if (val === '' || val === 'null') return null;
  return val;
}

function sqlEscape(val: string): string {
  return val.replace(/'/g, "''");
}

function formatArray(arr: string[]): string {
  if (arr.length === 0) return "'{}'";
  return `ARRAY[${arr.map(a => `'${sqlEscape(a)}'`).join(',')}]::text[]`;
}

function formatJson(val: string): string {
  if (!val || val === '{}') return "'{}'::jsonb";
  try {
    const parsed = JSON.parse(val);
    return `'${sqlEscape(JSON.stringify(parsed))}'::jsonb`;
  } catch { return "'{}'::jsonb"; }
}

function formatStr(val: string | null): string {
  if (val === null) return 'NULL';
  return `'${sqlEscape(val)}'`;
}

function formatNum(val: number | null): string {
  if (val === null) return 'NULL';
  return String(val);
}

function formatBool(val: boolean): string {
  return val ? 'true' : 'false';
}

// Read existing IDs from file (generated by a prior query)
let existingIds = new Set<string>();
try {
  const raw = readFileSync('scripts/existing_ids.json', 'utf8');
  existingIds = new Set(JSON.parse(raw));
  console.log(`Loaded ${existingIds.size} existing IDs`);
} catch {
  console.log('No existing_ids.json found - will include all records');
}

const raw = readFileSync(csvPath, 'utf8');
const rows = parseCSV(raw);
const headers = rows[0];
console.log(`CSV: ${rows.length - 1} data rows, ${headers.length} columns`);

const BATCH_SIZE = 50;
let batchNum = 0;
let totalGenerated = 0;
let totalSkipped = 0;

const columns = [
  'id', 'name', 'category_id', 'subcategory', 'description', 'address', 'city', 'county', 'state', 'zip_code',
  'phone', 'website', 'hours', 'accepts_uninsured', 'sliding_scale', 'medicaid', 'medicare', 'private_insurance',
  'walk_ins_welcome', 'appointments', 'telehealth', 'cost_free', 'cost_estimate_min', 'cost_estimate_max',
  'languages', 'accessibility', 'services', 'specialties', 'audiences', 'rating', 'photo_url', 'source',
  'google_place_id', 'created_at', 'updated_at', 'tags', 'search_text', 'domain', 'lat', 'lng', 'slug'
];

let currentBatch: string[] = [];

for (let r = 1; r < rows.length; r++) {
  const cells = rows[r];
  if (cells.length < headers.length) continue;

  const get = (col: string): string => {
    const idx = headers.indexOf(col);
    return idx >= 0 ? (cells[idx] ?? '') : '';
  };

  const id = get('id');
  if (!id) continue;

  if (existingIds.has(id)) {
    totalSkipped++;
    continue;
  }

  const values = [
    `'${sqlEscape(id)}'::uuid`,
    formatStr(get('name')),
    formatStr(parseStringOrNull(get('category_id'))) + (get('category_id') ? '::uuid' : ''),
    formatStr(get('subcategory') || ''),
    formatStr(get('description') || ''),
    formatStr(get('address') || ''),
    formatStr(get('city') || ''),
    formatStr(get('county') || ''),
    formatStr(get('state') || 'WA'),
    formatStr(get('zip_code') || ''),
    formatStr(get('phone') || ''),
    formatStr(parseStringOrNull(get('website'))),
    formatJson(get('hours')),
    formatBool(parseBool(get('accepts_uninsured'))),
    formatBool(parseBool(get('sliding_scale'))),
    formatBool(parseBool(get('medicaid'))),
    formatBool(parseBool(get('medicare'))),
    formatBool(parseBool(get('private_insurance'))),
    formatBool(parseBool(get('walk_ins_welcome'))),
    formatBool(parseBool(get('appointments'))),
    formatBool(parseBool(get('telehealth'))),
    formatBool(parseBool(get('cost_free'))),
    String(parseInt(get('cost_estimate_min')) || 0),
    String(parseInt(get('cost_estimate_max')) || 0),
    formatArray(parseArrayField(get('languages'))),
    formatArray(parseArrayField(get('accessibility'))),
    formatArray(parseArrayField(get('services'))),
    formatArray(parseArrayField(get('specialties'))),
    formatArray(parseArrayField(get('audiences'))),
    formatNum(parseFloatOrNull(get('rating'))),
    formatStr(get('photo_url') || ''),
    formatStr(get('source') || 'verified'),
    formatStr(parseStringOrNull(get('google_place_id'))),
    formatStr(get('created_at') || new Date().toISOString()),
    formatStr(get('updated_at') || new Date().toISOString()),
    formatArray(parseArrayField(get('tags'))),
    formatStr(parseStringOrNull(get('search_text'))),
    formatStr(parseStringOrNull(get('domain'))),
    formatNum(parseFloatOrNull(get('lat'))),
    formatNum(parseFloatOrNull(get('lng'))),
    formatStr(parseStringOrNull(get('slug'))),
  ];

  const sql = `INSERT INTO resources (${columns.join(', ')}) VALUES (${values.join(', ')});`;
  currentBatch.push(sql);
  totalGenerated++;

  if (currentBatch.length >= BATCH_SIZE) {
    const batchSql = currentBatch.join('\n');
    writeFileSync(`${outDir}/${String(batchNum).padStart(3, '0')}.sql`, batchSql);
    batchNum++;
    currentBatch = [];
  }
}

if (currentBatch.length > 0) {
  writeFileSync(`${outDir}/${String(batchNum).padStart(3, '0')}.sql`, currentBatch.join('\n'));
  batchNum++;
}

console.log(`Generated ${batchNum} batch files with ${totalGenerated} INSERT statements`);
console.log(`Skipped ${totalSkipped} records already in database`);
